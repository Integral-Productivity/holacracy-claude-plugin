#!/usr/bin/env python3
"""The GlassFrog tool inventory, and the coach's tool lists derived from it.

    python3 scripts/glassfrog-tool-inventory.py capture <glassfrog-mcp-server checkout>
        Print a fresh evals/glassfrog-tools.tsv from the server's source.
    python3 scripts/glassfrog-tool-inventory.py coach-frontmatter
        Print the `tools:` and `disallowedTools:` lines agents/holacracy-coach.md
        must carry, built from evals/glassfrog-tools.tsv and
        evals/glassfrog-server-prefixes.txt.

WHY A COMMITTED SNAPSHOT
------------------------
Skills cited seven tool names that existed on no server (#337), and the coach's
deny list missed the two newest write tools (#342). Both were hand-kept lists
that nothing compared against the server. skills-lint.sh checks 9 and 10 now
compare them against evals/glassfrog-tools.tsv. The lint runs offline on every
PR, where no glassfrog-mcp-server checkout exists, so the inventory is a
committed file and this script regenerates it. Read/write comes from each
tool's `readOnlyHint` annotation, not from its name.

WHY ONE NAME PER PREFIX
-----------------------
A subagent's tool entries are matched literally. Verified 2026-10-21 against
Claude Code 2.1.306 with a stub server under an arbitrary name: a wildcard in
the middle (`mcp__*__glassfrog_get_*`) matches nothing in `tools:` and blocks
nothing in `disallowedTools:`, and an entry that names no live tool is skipped
without error. So the coach lists every read tool under every known server
prefix. Under a prefix not in the list, the coach gets no GlassFrog tools at
all: it fails closed, never open (#338).
"""

import os
import re
import sys
from pathlib import Path

# skills-lint.sh points this at its fixture repos; normally it is this checkout.
ROOT = Path(os.environ.get("GLASSFROG_INVENTORY_ROOT") or Path(__file__).resolve().parent.parent)
INVENTORY = ROOT / "evals" / "glassfrog-tools.tsv"
PREFIXES = ROOT / "evals" / "glassfrog-server-prefixes.txt"
COACH_BASE_TOOLS = ["Read", "Glob", "Grep", "Write"]

HEADER = """\
# GlassFrog Extended tool inventory: <name> TAB <read|write>.
# Generated by: python3 scripts/glassfrog-tool-inventory.py capture <glassfrog-mcp-server>
# Do not hand-edit. Regenerate when the server adds, removes, or renames a tool,
# then regenerate the coach lines with `coach-frontmatter`. skills-lint.sh
# checks 9 and 10 read this file.
"""


def _rows(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            yield line


def load_inventory(path=INVENTORY):
    tools = {}
    for line in _rows(path):
        name, kind = line.split("\t")
        if kind not in ("read", "write"):
            raise SystemExit(f"{path}: bad kind {kind!r} for {name}")
        tools[name] = kind
    return tools


def load_prefixes(path=PREFIXES):
    return [line.split()[0] for line in _rows(path)]


def capture(server_repo):
    found = {}
    for ts in sorted(Path(server_repo, "src", "tools").glob("*.ts")):
        for block in re.split(r"registerTool\(\s*", ts.read_text(encoding="utf-8"))[1:]:
            m = re.match(r"['\"](glassfrog_[a-z_]+)['\"]", block)
            if not m:
                continue
            hint = re.search(r"readOnlyHint:\s*(true|false)", block)
            if not hint:
                raise SystemExit(f"{ts}: {m.group(1)} has no readOnlyHint")
            found[m.group(1)] = "read" if hint.group(1) == "true" else "write"
    if not found:
        raise SystemExit(f"no tools found under {server_repo}/src/tools")
    sys.stdout.write(HEADER)
    for name in sorted(found):
        sys.stdout.write(f"{name}\t{found[name]}\n")


def coach_frontmatter():
    tools = load_inventory()
    prefixes = load_prefixes()
    reads = sorted(n for n, k in tools.items() if k == "read")
    writes = sorted(n for n, k in tools.items() if k == "write")
    allow = COACH_BASE_TOOLS + [p + n for p in prefixes for n in reads]
    deny = [p + n for p in prefixes for n in writes]
    print("tools: " + ", ".join(allow))
    print("disallowedTools: " + ", ".join(deny))


def main(argv):
    if len(argv) == 3 and argv[1] == "capture":
        capture(argv[2])
    elif len(argv) == 2 and argv[1] == "coach-frontmatter":
        coach_frontmatter()
    else:
        sys.stderr.write(__doc__.split("\n\n")[1] + "\n")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
